#!/usr/bin/env bash
# الخطوة 2: ينسخ التسجيلات من mp3/ (مجلدات بأسماء عربية) إلى SD_card/mp3_untrimmed/ بأسماء رقمية 4 خانات،
# ويكتب جدول المطابقة. بعده: trim_silence.ps1 ثم build_phrases.ps1.
#   bash tools/organize_sounds.sh "<مجلد المشروع>"
set -e
SRC="$1/mp3"
OUT="$1/SD_card/mp3_untrimmed"
TABLE="$1/SD_card/جدول_الأصوات.csv"
mkdir -p "$OUT"
echo "id,file,category,source" > "$TABLE"
n=0
put() { # id category source
  local id; id=$(printf "%04d" "$1")
  [ -f "$SRC/$3" ] || { echo "MISSING: $3"; exit 1; }
  cp "$SRC/$3" "$OUT/$id.mp3"
  echo "$id,$id.mp3,$2,$3" >> "$TABLE"
  n=$((n+1))
}

# التحية والاسم
put 1 "تحية" "صباح مساء/صباح الخير.mp3"
put 2 "تحية" "صباح مساء/مساء لخير.mp3"
put 3 "تحية" "كلمات مساعده/يا.mp3"
put 4 "الاسم" "اسمي/عبد العزيز.mp3"
put 5 "صباحاً" "صباح مساء/ص.mp3"
put 6 "مساءً" "صباح مساء/س.mp3"

# نغمات التنبيه
put 10 "تنبيه مستوى 3" "تنبيهات/تنبيه بسيط.mp3"
put 11 "تنبيه مستوى 2" "تنبيهات/تنبيه متوسط.mp3"
put 12 "تنبيه مستوى 1" "تنبيهات/تنبيه عالي الخطورة.mp3"

# أيام الأسبوع: 40 + dayOfTheWeek (الأحد = 0 في RTClib)
days=(الاحد الاثنين الثلاثاء الاربعاء الخميس الجمعه السبت)
for i in "${!days[@]}"; do put $((40+i)) "يوم الأسبوع" "ايام الاسبوع/${days[$i]}.mp3"; done

# كلمات مساعدة
put 50 "كلمة مساعدة" "كلمات مساعده/الساعه الان.mp3"
put 51 "كلمة مساعدة" "كلمات مساعده/اليوم هو.mp3"
put 52 "كلمة مساعدة" "كلمات مساعده/تاريخ اليوم هو.mp3"
put 53 "كلمة مساعدة" "كلمات مساعده/من.mp3"
put 54 "كلمة مساعدة" "كلمات مساعده/و.mp3"

# الأشهر: 60 + الشهر
months=(يناير فبراير مارس أبريل مايو يونيو يوليو أغسطس سبتمبر أكتوبر نوفمبر ديسمبر)
for i in "${!months[@]}"; do put $((61+i)) "شهر" "اسما الشهر/${months[$i]}.mp3"; done

# الساعات: 80 + الساعة
put 81 "ساعة" "الساعة/الساعة الواحدة.mp3"
put 82 "ساعة" "الساعة/الساعة الثانية.mp3"
for h in $(seq 3 12); do put $((80+h)) "ساعة" "الساعة/$h.mp3"; done

# الدقائق: 100 + الدقيقة
put 101 "دقيقة" "دقيقه/دقيقة واحدة.mp3"
put 102 "دقيقة" "دقيقه/دقيقتان.mp3"
put 103 "دقيقة" "دقيقه/ثلاث دقائق.mp3"
for m in $(seq 4 59); do put $((100+m)) "دقيقة" "دقيقه/$m.mp3"; done

# السنوات: 200 + (السنة - 2000)
for y in 2026 2027 2028; do put $((200+y-2000)) "سنة" "سنوات/$y.mp3"; done

# أيام الشهر: 300 + اليوم
ord=(الأول الثاني الثالث الرابع الخامس السادس السابع الثامن التاسع العاشر
     "الحادي عشر" "الثاني عشر" "الثالث عشر" "الرابع عشر" "الخامس عشر"
     "السادس عشر" "السابع عشر" "الثامن عشر" "التاسع عشر" العشرون
     "الحادي والعشرون" "الثاني والعشرون" "الثالث والعشرون" "الرابع والعشرون"
     "الخامس والعشرون" "السادس والعشرون" "السابع والعشرون" "الثامن والعشرون"
     "التاسع والعشرون" الثلاثون "الحادي والثلاثون")
for i in "${!ord[@]}"; do put $((301+i)) "يوم الشهر" "أيام الشهر/${ord[$i]}.mp3"; done

echo "COPIED: $n"
